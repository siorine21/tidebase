-- ============================================================
-- 立ち位置に「ボート」を足し、未設定を埋める。スポット種別も埋める
--
-- 要望（2026-08-10）:
--   ・ウェーディングと書いてあるもの以外は、おかっぱりにしてほしい
--   ・スポット種別が入っていないものを入れてほしい
--
-- **028 の「値は 2 つだけで足りる」を取り消す。**
-- 種別の無い 7 件を埋めるために 1 件ずつ確認したところ、「えびすき漁」は
-- **浜名湖の橋脚下で、船に乗ってやる**場所だと分かった。
-- おかっぱりでもウェーディングでもない。立ち位置の軸は「どこに身を置くか」
-- （岸 / 水の中 / 船の上）なので、boat はこの軸の 3 つ目として素直に収まる。
--
-- 潮位の効き方も 3 つで違う。おかっぱりは潮位をあまり選ばない、
-- 立ち込みは満潮では入れないことがある、船は出せるかどうかが風と潮で決まる。
-- 釣行スコアに効かせるとき、ここが 2 値だと船を岸と同じ扱いにしてしまう。
--
-- **決めつけで埋めることになるのは承知の上**（028 では避けた）。
-- 本人が「ウェーディング以外はおかっぱり」と明言したので、その通りにする。
-- 以後に登録するぶんは未設定のままにできる（NULL は残す）。
-- ============================================================

BEGIN;

-- ------------------------------------------------------------
-- 1. boat を許可する
-- ------------------------------------------------------------
ALTER TABLE public.spots
  DROP CONSTRAINT IF EXISTS spots_entry_style_check;
ALTER TABLE public.spots
  ADD CONSTRAINT spots_entry_style_check
  CHECK (entry_style IS NULL OR entry_style IN ('bank', 'wading', 'boat'));

COMMENT ON COLUMN public.spots.entry_style IS
  '立ち位置: bank おかっぱり / wading ウェーディング / boat ボート。NULL は未設定。'
  'spot_type（場所の種類）とは別の軸。同じ河口でも 3 つともありうる。';

-- ------------------------------------------------------------
-- 2. 船で出る場所を先に決める（次の一括更新に巻き込まれないよう先に）
-- ------------------------------------------------------------
UPDATE public.spots
   SET entry_style = 'boat'
 WHERE name = 'えびすき漁';

-- ------------------------------------------------------------
-- 3. 残りの未設定をおかっぱりにする
--    ウェーディングと boat は上で入っているので触らない
-- ------------------------------------------------------------
UPDATE public.spots
   SET entry_style = 'bank'
 WHERE entry_style IS NULL;

-- ------------------------------------------------------------
-- 4. スポット種別が空のものを埋める
--    名前と座標から決まるものだけ。既に入っているものは上書きしない
--    （spot_type IS NULL を必ず付ける）
-- ------------------------------------------------------------
UPDATE public.spots SET spot_type = 'surf'
 WHERE spot_type IS NULL AND name = '中田島サーフ';

UPDATE public.spots SET spot_type = 'rivermouth'
 WHERE spot_type IS NULL AND name IN (
   '天竜川河口(磐田側)', '弁財天川河口', '太田川ワンド', '太田川ワンド(ウェーディング)');

UPDATE public.spots SET spot_type = 'port'
 WHERE spot_type IS NULL AND name = '新居漁港';

-- 浜名湖そのもの。橋脚まわりで船から釣る場所なので、場所の種類は汽水湖
UPDATE public.spots SET spot_type = 'brackish_lake'
 WHERE spot_type IS NULL AND name = 'えびすき漁';

COMMIT;
