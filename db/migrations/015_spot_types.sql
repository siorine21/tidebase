-- ============================================================
-- スポット種別を拡充する
--
-- 要望（2026-08-08）: 河口域や干潟などを足したい。
--
-- 既存の 5 種（サーフ・磯・港湾・管理釣り場・河川）は外洋と淡水に偏っていて、
-- **汽水域がまるごと抜けていた**。浜名湖を主戦場にしている以上、
-- 河口・干潟・汽水湖・水路が無いと、ほとんどのスポットが「未設定」になる。
--
-- 分類の軸は「釣り方が変わるかどうか」。地形が同じでも狙い方が同じなら分けない。
--   - ゴロタ場はサーフと磯の中間で、扱うルアーもレンジも違うので独立させる
--   - テトラ帯は港湾の中にもサーフ沿いにもあり、足場と狙う魚が変わるので独立させる
--   - 堤防は港湾と実質同じ釣り方なので「港湾・堤防」にまとめ、種別は増やさない
-- ============================================================

BEGIN;

ALTER TABLE public.spots DROP CONSTRAINT IF EXISTS spots_spot_type_check;

ALTER TABLE public.spots ADD CONSTRAINT spots_spot_type_check CHECK (
  spot_type IS NULL OR spot_type IN (
    -- 海
    'surf',          -- サーフ（砂浜）
    'cobble',        -- ゴロタ場（石浜）
    'rock',          -- 磯
    'port',          -- 港湾・堤防
    'tetra',         -- テトラ帯（消波ブロック）
    -- 汽水
    'rivermouth',    -- 河口
    'tidalflat',     -- 干潟
    'brackish_lake', -- 汽水湖
    'channel',       -- 水路・運河
    -- 淡水
    'river',         -- 河川
    'lake',          -- 湖沼・池
    'managed'        -- 管理釣り場
  )
);

COMMENT ON COLUMN public.spots.spot_type IS
  'スポット種別。釣り方が変わる粒度で分ける（詳細は 015 のコメント）。NULL は未設定。';

COMMIT;
