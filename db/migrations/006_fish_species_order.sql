-- ============================================================
-- 魚種マスタの拡充と並び順の整備
--
-- 1) 魚種を 7 種追加（アジ・メバル・カサゴ・カマス・キス・イカ・タコ）
-- 2) sort_order を追加し、水域区分ごとに近縁種を隣接させて並べる
--
-- グルーピングの根拠（確定仕様書 1.1 章「主なフィールド」）:
--   クロダイ = 港湾・磯・河川 / キビレ = 河川・干潟 → いずれも汽水域が主戦場のため
--   両者を汽水にまとめ、チヌ系として隣接させる。
-- ============================================================

BEGIN;

ALTER TABLE public.fish_species
  ADD COLUMN IF NOT EXISTS sort_order INTEGER;

-- ------------------------------------------------------------
-- 追加する魚種（すべてシステムデフォルト = user_id NULL）
-- ------------------------------------------------------------
INSERT INTO public.fish_species (user_id, name, category) VALUES
  (NULL, 'カマス',  '海水'),
  (NULL, 'メバル',  '海水'),
  (NULL, 'カサゴ',  '海水'),
  (NULL, 'アジ',    '海水'),
  (NULL, 'キス',    '海水'),
  (NULL, 'イカ',    '海水'),
  (NULL, 'タコ',    '海水')
ON CONFLICT (user_id, name) DO NOTHING;

-- ------------------------------------------------------------
-- 水域区分と並び順（近縁種・釣り方が近いものを隣接させる）
-- ------------------------------------------------------------
UPDATE public.fish_species AS f
SET category = v.category, sort_order = v.sort_order
FROM (VALUES
  -- 海水
  ('マルスズキ',   '海水',  10),   -- スズキ系（出世魚）
  ('ヒラスズキ',   '海水',  20),
  ('ブリ',         '海水',  30),   -- 青物（出世魚）
  ('サワラ',       '海水',  40),
  ('カマス',       '海水',  50),   -- 細長い回遊魚
  ('タチウオ',     '海水',  60),
  ('ヒラメ',       '海水',  70),   -- フラットフィッシュ
  ('マゴチ',       '海水',  80),
  ('メバル',       '海水',  90),   -- 根魚
  ('カサゴ',       '海水', 100),
  ('アジ',         '海水', 110),   -- 小型回遊魚
  ('キス',         '海水', 120),   -- 投げ釣り
  ('イカ',         '海水', 130),   -- 頭足類
  ('タコ',         '海水', 140),
  -- 汽水（チヌ系）
  ('クロダイ',     '汽水',  10),
  ('キビレ',       '汽水',  20),
  -- 淡水
  ('トラウト',     '淡水',  10),
  ('ブラックバス', '淡水',  20),
  ('ライギョ',     '淡水',  30),
  ('ナマズ',       '淡水',  40)
) AS v(name, category, sort_order)
WHERE f.user_id IS NULL AND f.name = v.name;

COMMIT;
