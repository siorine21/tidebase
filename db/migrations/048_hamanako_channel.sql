-- ============================================================
-- 浜名湖のカメラを、動画ではなくチャンネルで指す
--
-- 047 で舞阪漁港の**動画 ID**（lLG9L053onI）を入れたが、
-- **1 日ももたずに再生不可になった。**
--
-- これは 045（D-145）で書いたとおりのことがそのまま起きただけ。
-- 「YouTube のライブは、配信する側が配信を切り直すたびに動画 ID が変わる」。
-- 分かっていながら動画 ID で入れたのは、この環境から youtube.com が 403 で
-- 見えず、@ハンドルから UC を引けなかったため。**引けない理由は、
-- 動画 ID で妥協してよい理由にはならなかった。**
--
-- チャンネル ID は検索から取れた（ZAZA マガジンチャンネル）。
-- 同笠と同じ `embed/live_stream?channel=` に切り替える。
--
-- **ただし同笠と条件が違う。** 同笠のチャンネルはそのカメラ専用だが、
-- ZAZA は雑誌のチャンネルで、浜名湖のカメラを 2 台（舞阪漁港・
-- ガーデンパーク）出しているうえ、催しの中継もする。
-- `live_stream?channel=` は「そのチャンネルがいま生放送しているもの」を
-- 出すので、**どれが映るかはこちらで選べない。**
-- 名前と note でそう書いておく。黙って別のものが映るほうが悪い。
--
-- 座標は 047 のまま入れない。湖の中に沖の波高を出しても読む意味が無い（D-142）。
-- ============================================================

BEGIN;

UPDATE public.live_cameras
SET youtube_channel_id = 'UCJKH8wYxFYeufDnvy1MPofA',
    youtube_id = NULL,                      -- **1 つだけが正**（045 の CHECK）
    name = '浜名湖',
    note = 'ZAZA マガジンの浜名湖のライブ。舞阪漁港（浜名大橋・弁天島の方向）か'
           || 'ガーデンパークのどちらかが映る。表浜名湖の濁りを見たいのは舞阪のほう'
WHERE code = 'HAMANA-MAISAKA';

COMMIT;
