-- ============================================================
-- 029 で埋めた種別のうち 2 件を直し、名前を付け替える
--
-- 指摘（2026-08-10）: 天竜川河口(磐田側) と 弁財天川河口 の種別はサーフ。
--   天竜川河口(磐田側) → 天竜川河口(東側)
--   弁財天川河口       → 弁財天川河口(東側)
--
-- **名前に「河口」と入っているから河口だと決めた 029 の推測が外れた。**
-- 河口という地名で呼んでいても、実際に立つのは隣接するサーフのほう。
-- 名前の文字列から種別を当てるのは、ここまでが限界だと分かった
-- （実際に通っている本人にしか決められない）。
--
-- 名前の「(東側)」は本人の指定どおり。どちら岸に入るかで
-- 駐車場所も足場も変わるので、名前で分かるようにしておく。
-- ============================================================

BEGIN;

UPDATE public.spots
   SET spot_type = 'surf', name = '天竜川河口(東側)'
 WHERE name = '天竜川河口(磐田側)';

UPDATE public.spots
   SET spot_type = 'surf', name = '弁財天川河口(東側)'
 WHERE name = '弁財天川河口';

COMMIT;
