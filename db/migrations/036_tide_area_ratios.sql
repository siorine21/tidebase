-- 036: 浜名湖の細分地点の潮高比と時差を、実測にもとづく値へ更新する（D-133）
--
-- これまで 9 地点すべて level_ratio = 1.00 だった。時差だけ入れて振幅は舞阪と
-- 同じ、という状態で、奥浜名湖でも外海と同じだけ潮位が振れる計算になっていた。
-- 実際には今切口が狭窄部として効いていて、湖奥ほど振幅は小さい。
--
-- 出典（確かさの段階を note に残す）:
--   ① 直接実測      … その地点そのものを測った値
--   ② 実測＋経年補正 … 1972 年実測に、その後の増加ぶんを足したもの
--   ③ 推定          … 実測なし。近隣から内挿・外挿したもの
--
--   [A] 野中忠・村松高明・鈴木克宏・平井亨「浜名湖浅海開発工事の効果
--       ― 海水交流について ―」水産土木 Vol.10 No.1, 47-51（1972 年観測）
--       表-4「湖内各所の日潮差と日潮差比」/ 図-4「舞阪からの潮位のおくれ」
--   [B]「猪鼻湖における底層貧酸素水のエアレーション効果の検討」
--       海岸工学論文集 第48巻(2001), 1067-（1999 年 水圧計連続観測）
--       猪鼻湖は舞阪比で振幅 50〜60%、位相 約 3 時間遅れ。
--       外洋（赤羽根）と舞阪は「位相差ほとんどなし・振幅は舞阪が 10% 小さい」
--
-- [A] は 1972 年の値で、その後の浚渫で振幅比は増えている（[A] 自身が
-- 1965→1968→1972 の増加を記録し、さらに工事が続くと注記している）。
-- [B] の猪鼻湖 0.55 と [A] の猪鼻口 0.38 の差 +0.17 を、[A] の各地点へ
-- 一律に足して現在値とした。これが「②実測＋経年補正」。
--
-- **潮高比はスコアには使わない**（D-133）。スコアは「その地点の大潮基準に
-- 対する比」で見るので、潮高比は約分されて消える。ここで入れる値が効くのは
-- 潮位グラフの表示だけで、ずれていれば画面を見れば気づける。

