BEGIN;

-- 038: 観測所ごとの「大潮の最大流速」を持つ（D-135）
--
-- 釣行スコアで潮の強さを見るのに、**その地点の大潮を 1 とした比**を使う。
-- 絶対値（cm/h）で線を引くと、潮高比のわずかな誤差でスコアが大きく動く
-- （実測: 潮高比 0.75 と 0.95 で、条件の当たる時間が 11% と 22%・D-133）。
-- 比で見れば潮高比は分子と分母の両方に掛かって**約分される**。
--
-- 値の出し方: 気象庁の潮位表推算値（tide Edge Function）から、
-- 暦で大潮の 8 日（2026-03〜08）を取り、毎時値の前後 30 分差で流速を出し、
-- その日の最大の**中央値**を採った。流速の測り方は tideFlowAt と同じ。
--
-- 15 局で「最大流速 ÷ 潮位差」は 0.221〜0.243 にそろっており、
-- 潮位差から幾何的に決まる量であることが確かめられた（局によらない）。
-- それでも定数を持つのは、**単日から逆算すると誤差が大きい**ため
-- （潮回り 5 段階で中央 9%・最大 30%、月齢の当てはめでも 11% のばらつき）。
--
-- **入っていない局は、潮の強さの条件を「対象外」として数から外す。**
-- 淡水スポットで潮の条件が使えないのと同じ扱いで、点は残りの条件で決まる。
-- 全 239 局のうち、静岡県 12 局と近隣（三河・赤羽根・小田原・油壺・名古屋）を入れた。
-- 足すのはデータだけの追加でできる。

ALTER TABLE public.tide_stations
  ADD COLUMN IF NOT EXISTS spring_flow_cm_h NUMERIC;

COMMENT ON COLUMN public.tide_stations.spring_flow_cm_h IS
  '大潮の日の最大流速（cm/h、潮位の前後 30 分差）。釣行スコアで「潮がよく流れているか」を'
  'その地点の大潮を 1 とした比で見るための基準（D-135）。'
  '気象庁の潮位表推算値から、暦で大潮の 8 日ぶんの日最大の中央値。'
  'NULL の局では潮の強さの条件を対象外にする（点は残りの条件で決まる）。'
  '細分地点では潮高比を掛けて使う（そうすると比の計算で潮高比が約分される）。';

UPDATE public.tide_stations SET spring_flow_cm_h = v.f
FROM (VALUES
  ('MI', 27),   -- 舞阪
  ('OM', 35),   -- 御前崎
  ('SM', 32),   -- 清水港
  ('Z5', 34),   -- 焼津
  ('D6', 33),   -- 下田
  ('G9', 33),   -- 石廊崎
  ('QK', 33),   -- 南伊豆
  ('UC', 34),   -- 内浦
  ('Z3', 30),   -- 伊東
  ('Z4', 33),   -- 田子
  ('Z1', 30),   -- 油壺（神奈川県・三浦半島のスポットで使用）
  ('OD', 29),   -- 小田原
  ('I4', 37),   -- 赤羽根（愛知県・遠州灘の外洋側）
  ('G4', 50),   -- 三河
  ('NG', 53)    -- 名古屋
) AS v(code, f)
WHERE public.tide_stations.code = v.code;

COMMIT;
