-- ============================================================
-- 「二瀬北　チヌトップ(ウェーディング)」の水域を汽水に直す
--
-- D-160 でおすすめスポットの除外条件を決めるときに見つけた付け間違い。
--
-- **根拠は記録そのもの。** このスポットで釣れているのは**クロダイ 40cm**
-- （2025-08-03）で、もう 1 件も「出るけど掛からん」というチヌのバイト。
-- クロダイは汽水〜海水の魚で、淡水域にはいない。
-- 名前にある「チヌトップ」もそれを指している。
--
-- 同じ水系の 600m 下流にある「二瀬橋(ウェーディング)」は brackish で
-- 潮汐地点 MI を持っている。ここだけ freshwater になっていた。
--
-- **何が起きていたか**: 淡水と書かれていたため 037 のトリガーが
-- 潮汐地点を付けず、結果として
--   - 潮位置（上げ◯分）が入らない
--   - おすすめスポットの候補から外れる（潮汐が効かない場所として）
-- という扱いになっていた。どちらも黙って起きるので、画面からは気づけない。
--
-- **tide_influence ではなく water_type を直す。** 037 の tide_influence は
-- 「淡水だが潮位は動く」（感潮域）のための軸で、塩分そのものは淡水のまま。
-- ここは塩分が淡水ではないので、当てはまらない。
--
-- 水域を汽水に変えると 037 のトリガーが潮汐地点を付け直す
-- （water_type が変わると coords_changed が立つ）。
--
-- **名前で 1 行だけ狙い、いまの値が間違っているときにだけ当てる。**
-- 2 回当てても何も起きないし、まっさらな DB では 1 行も当たらない。
--
-- 潮位置は別に埋め戻す（scripts/backfill_tide_phase.mjs）。
-- 画面から見える変化はスポットの水域表示だけなので、
-- お知らせは D-160 の 1 件へまとめる（D-109）。
-- ============================================================

BEGIN;

UPDATE public.spots
SET water_type = 'brackish'
WHERE name = '二瀬北　チヌトップ(ウェーディング)'
  AND water_type = 'freshwater';

COMMIT;
